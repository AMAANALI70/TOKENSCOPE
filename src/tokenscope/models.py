"""Provider-neutral data model.

Every parser converts a provider-specific request/response into these types.
Everything downstream (attribution, detectors, optimizers) only sees this model,
so adding a provider means adding one parser and nothing else.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Any


class Category(str, Enum):
    """What a chunk of tokens *is*, from the agent developer's point of view."""

    SYSTEM = "system"
    TOOL_SCHEMA = "tool_schema"  # tool/function definitions sent on every call
    USER = "user"
    ASSISTANT = "assistant"  # assistant text/thinking replayed as history
    TOOL_CALL = "tool_call"  # assistant tool-call arguments replayed as history
    TOOL_RESULT = "tool_result"  # tool outputs replayed as history
    OUTPUT = "output"  # tokens generated by the model in this call


INPUT_CATEGORIES: tuple[Category, ...] = tuple(c for c in Category if c is not Category.OUTPUT)


class UsageProvenance(str, Enum):
    """Where token usage metrics originated."""

    PROVIDER = "provider"
    ESTIMATED = "estimated"
    UNKNOWN = "unknown"


@dataclass(frozen=True, slots=True)
class Segment:
    """A contiguous piece of text with a category. The unit of attribution."""

    category: Category
    text: str
    tool_name: str | None = None
    message_index: int | None = None  # position in the request's message list


@dataclass(frozen=True, slots=True)
class ToolDefinition:
    """Provider-neutral representation of a tool or function specification."""

    name: str
    description: str | None = None
    parameters: dict[str, Any] = field(default_factory=dict)
    raw_schema: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True, slots=True)
class ToolCall:
    """Provider-neutral representation of an assistant tool call."""

    id: str | None
    name: str
    arguments: str
    parsed_arguments: dict[str, Any] | None = None


@dataclass(frozen=True, slots=True)
class ToolResult:
    """Provider-neutral representation of a tool execution result."""

    tool_call_id: str | None
    name: str | None
    content: str
    is_error: bool = False
    raw_content: Any = None


@dataclass(frozen=True, slots=True)
class ContentBlock:
    """Provider-neutral structured content item (text, thinking, image, etc.)."""

    type: str
    text: str | None = None
    data: Any = None


@dataclass(frozen=True, slots=True)
class Message:
    """Provider-neutral structured representation of a conversation turn."""

    role: str  # "system", "developer", "user", "assistant", "tool"
    content: str | list[ContentBlock] | None = None
    name: str | None = None
    tool_calls: list[ToolCall] = field(default_factory=list)
    tool_call_id: str | None = None
    tool_result: ToolResult | None = None


@dataclass(frozen=True, slots=True)
class Usage:
    """Provider-reported or estimated token usage, normalised.

    ``input_tokens`` (and ``total_input_tokens``) is the TOTAL prompt size including
    both uncached and cached tokens, ensuring consistency across providers.

    Enforces the invariant:
    total input = uncached input + cache-read input + cache-creation input.
    """

    input_tokens: int
    output_tokens: int
    cached_input_tokens: int = 0
    uncached_input_tokens: int | None = None
    cache_read_input_tokens: int | None = None
    cache_creation_input_tokens: int = 0
    cache_creation_details: dict[str, int] = field(default_factory=dict)
    provenance: UsageProvenance = UsageProvenance.PROVIDER

    def __post_init__(self) -> None:
        if self.input_tokens < 0 or self.output_tokens < 0:
            raise ValueError(
                f"Token counts cannot be negative: input={self.input_tokens}, "
                f"output={self.output_tokens}"
            )
        if self.cached_input_tokens < 0 or self.cache_creation_input_tokens < 0:
            raise ValueError("Token counts cannot be negative")

        read_val = self.cache_read_input_tokens
        if read_val is None:
            read_val = self.cached_input_tokens
            object.__setattr__(self, "cache_read_input_tokens", read_val)
        elif self.cached_input_tokens == 0 and read_val != 0:
            object.__setattr__(self, "cached_input_tokens", read_val)
        elif self.cached_input_tokens != read_val:
            raise ValueError(
                f"Conflicting cached_input_tokens ({self.cached_input_tokens}) "
                f"and cache_read_input_tokens ({read_val})"
            )

        if read_val < 0:
            raise ValueError(f"Cache-read tokens cannot be negative: {read_val}")

        # Preserve and validate cache creation details (e.g. Anthropic 5m vs 1h TTL)
        if self.cache_creation_details:
            for k, v in self.cache_creation_details.items():
                if v < 0:
                    raise ValueError(f"Cache creation detail {k} cannot be negative: {v}")
            details_sum = sum(self.cache_creation_details.values())
            if self.cache_creation_input_tokens == 0 and details_sum > 0:
                object.__setattr__(self, "cache_creation_input_tokens", details_sum)
            elif details_sum > self.cache_creation_input_tokens:
                raise ValueError(
                    f"Sum of cache_creation_details ({details_sum}) exceeds "
                    f"cache_creation_input_tokens ({self.cache_creation_input_tokens})"
                )

        if self.uncached_input_tokens is not None:
            if self.uncached_input_tokens < 0:
                raise ValueError(
                    f"Uncached tokens cannot be negative: {self.uncached_input_tokens}"
                )
            expected_total = (
                self.uncached_input_tokens + read_val + self.cache_creation_input_tokens
            )
            if self.input_tokens != expected_total:
                raise ValueError(
                    f"Inconsistent token counts: total input ({self.input_tokens}) != "
                    f"uncached ({self.uncached_input_tokens}) + cache_read ({read_val}) + "
                    f"cache_creation ({self.cache_creation_input_tokens})"
                )
        else:
            computed_uncached = self.input_tokens - read_val - self.cache_creation_input_tokens
            if computed_uncached < 0:
                raise ValueError(
                    f"Inconsistent token counts: total input ({self.input_tokens}) is less than "
                    f"cache_read ({read_val}) + cache_creation ({self.cache_creation_input_tokens})"
                )
            object.__setattr__(self, "uncached_input_tokens", computed_uncached)

    @property
    def total_input_tokens(self) -> int:
        return self.input_tokens


@dataclass(slots=True)
class Call:
    """One LLM request (and optionally its response) inside an agent run."""

    index: int
    model: str | None
    input_segments: list[Segment]
    output_segments: list[Segment] = field(default_factory=list)
    usage: Usage | None = None
    call_id: str | None = None
    execution_id: str | None = None
    messages: list[Message] = field(default_factory=list)
    tools: list[ToolDefinition] = field(default_factory=list)
    response_messages: list[Message] = field(default_factory=list)
    metadata: dict[str, Any] = field(default_factory=dict)
    provider: str | None = None


@dataclass(slots=True)
class Trace:
    """An ordered list of calls that make up one agent run."""

    calls: list[Call]
    source_format: str
    trace_id: str | None = None
    execution_id: str | None = None
    metadata: dict[str, Any] = field(default_factory=dict)
